package reporting

import (
	"fmt"
	"os"
	"path/filepath"

	"aventinelabs.com/testudo-jmx/pkg/engine"
)

// GenerateStaticDashboard outputs a self-contained HTML dashboard report matching JMeter's -e -o feature.
func GenerateStaticDashboard(reportDir string, snap engine.MetricSnapshot, scenarioName string) error {
	if err := os.MkdirAll(reportDir, 0755); err != nil {
		return fmt.Errorf("failed to create report directory: %w", err)
	}

	htmlPath := filepath.Join(reportDir, "index.html")

	html := fmt.Sprintf(`<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <title>Testudo-JMX Report - %s</title>
  <style>
    :root {
      --bg: #090d16;
      --card-bg: #111827;
      --border: #1f2937;
      --text: #f3f4f6;
      --text-muted: #9ca3af;
      --accent: #38bdf8;
      --success: #22c55e;
      --danger: #ef4444;
    }
    body {
      font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif;
      background: var(--bg);
      color: var(--text);
      margin: 0;
      padding: 32px;
    }
    .header {
      display: flex;
      justify-content: space-between;
      align-items: center;
      border-bottom: 1px solid var(--border);
      padding-bottom: 20px;
      margin-bottom: 24px;
    }
    .badge {
      background: #0b0f19;
      border: 1px solid rgba(255,255,255,0.15);
      border-radius: 6px;
      padding: 6px 14px;
      font-size: 13px;
      font-weight: 700;
      color: var(--accent);
      letter-spacing: 0.05em;
    }
    .grid {
      display: grid;
      grid-template-columns: repeat(auto-fit, minmax(220px, 1fr));
      gap: 16px;
      margin-bottom: 24px;
    }
    .card {
      background: var(--card-bg);
      border: 1px solid var(--border);
      border-radius: 8px;
      padding: 20px;
    }
    .card-title {
      font-size: 12px;
      text-transform: uppercase;
      color: var(--text-muted);
      margin-bottom: 8px;
    }
    .card-val {
      font-size: 26px;
      font-weight: 700;
      color: var(--accent);
    }
    .table-container {
      background: var(--card-bg);
      border: 1px solid var(--border);
      border-radius: 8px;
      overflow: hidden;
    }
    table {
      width: 100%%;
      border-collapse: collapse;
      text-align: left;
    }
    th, td {
      padding: 12px 16px;
      border-bottom: 1px solid var(--border);
    }
    th {
      background: #1e293b;
      font-size: 12px;
      text-transform: uppercase;
      color: var(--text-muted);
    }
  </style>
</head>
<body>
  <div class="header">
    <div>
      <h1 style="margin:0 0 4px 0; font-size:24px;">Testudo-JMX Execution Dashboard</h1>
      <div style="color:var(--text-muted); font-size:14px;">Scenario: %s</div>
    </div>
    <div class="badge">[ TESTUDO SUITE ]</div>
  </div>

  <div class="grid">
    <div class="card">
      <div class="card-title">Total Requests</div>
      <div class="card-val">%d</div>
    </div>
    <div class="card">
      <div class="card-title">Throughput</div>
      <div class="card-val">%.1f req/s</div>
    </div>
    <div class="card">
      <div class="card-title">Error Rate</div>
      <div class="card-val" style="color:%s">%.2f%%</div>
    </div>
    <div class="card">
      <div class="card-title">Latency P95</div>
      <div class="card-val">%.1f ms</div>
    </div>
    <div class="card">
      <div class="card-title">Latency P99</div>
      <div class="card-val">%.1f ms</div>
    </div>
  </div>

  <div class="table-container">
    <table>
      <thead>
        <tr>
          <th>Metric</th>
          <th>p50 (Median)</th>
          <th>p90</th>
          <th>p95</th>
          <th>p99</th>
          <th>Max</th>
        </tr>
      </thead>
      <tbody>
        <tr>
          <td><strong>Response Time (ms)</strong></td>
          <td>%.1f ms</td>
          <td>%.1f ms</td>
          <td>%.1f ms</td>
          <td>%.1f ms</td>
          <td>%.1f ms</td>
        </tr>
      </tbody>
    </table>
  </div>
  <div style="margin-top:20px; text-align:center; font-size:12px; color:var(--text-muted);">
    Generated by Testudo-JMX Native Engine &bull; Aventine Labs LLC &bull; 100%% Java-Free Architecture
  </div>
</body>
</html>`,
		scenarioName,
		scenarioName,
		snap.TotalRequests,
		snap.RequestsPerSec,
		func() string {
			if snap.ErrorRatePct > 1.0 {
				return "var(--danger)"
			}
			return "var(--success)"
		}(),
		snap.ErrorRatePct,
		snap.LatencyP95Ms,
		snap.LatencyP99Ms,
		snap.LatencyP50Ms,
		snap.LatencyP90Ms,
		snap.LatencyP95Ms,
		snap.LatencyP99Ms,
		snap.LatencyMaxMs,
	)

	return os.WriteFile(htmlPath, []byte(html), 0644)
}
